GRAVITON = {"6": "Graviton2", "7": "Graviton3", "8": "Graviton4", "9": "Graviton5"}


def fm_list(text, key):
    """Entries of a frontmatter list (`images:` / `images_x86_64:`)."""
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    lm = re.search(rf"^{key}:\s*\n((?:\s+-\s+.*\n?)+)", m.group(1) + "\n", re.M) if m else None
    return re.findall(r"^\s+-\s+(\S+)", lm.group(1), re.M) if lm else []


def unq(v):
    return v.strip().strip('"').strip("'") if isinstance(v, str) else v


def chip_of(instance):
    """arch / vendor / generation from an instance name; None where the family says nothing."""
    m = re.match(r"([a-z]+)(\d+)([a-z]*)", instance)
    if not m:
        return {}
    fam, gen, suf = m.groups()
    if suf.startswith("g"):
        return {"arch": "arm64", "vendor": "AWS", "chip": GRAVITON.get(gen), "generation": int(gen)}
    if suf.startswith("i"):
        return {"arch": "x86_64", "vendor": "Intel", "generation": int(gen)}
    if suf.startswith("a"):
        return {"arch": "amd", "vendor": "AMD", "generation": int(gen)}
    return {"generation": int(gen)}


def host_facts(path):
    """threads_per_core, CPU part, model and OpenBLAS corename from a run's host-facts file, in
    the key spellings the results/ files actually use."""
    try:
        t = open(path, encoding="utf-8", errors="replace").read()
    except OSError:
        return {}
    out = {}
    for key, pat in (("threads_per_core", r"(?:threads_per_core|Thread\(s\) per core)[^\n\d]{0,40}?(\d+)"),
                     ("cpu_part", r"CPU part\s*:\s*(0x[0-9a-f]+)"),
                     ("cpu_model", r"model name\s*:\s*(.+)"),
                     ("openblas_corename", r"openblas_corename\W{1,4}([A-Za-z][\w]*)"),
                     ("cpus_online", r"cpus_online\W{1,4}(\d+)"),
                     ("blas", r"(?:libblas_target|lib_libblas\.so\.3)\s+\S*?(lib(?:openblas|mkl_rt|blis|blas)[\w.-]*)")):
        m = re.search(pat, t)
        if m:
            out[key] = int(m.group(1)) if key in ("threads_per_core", "cpus_online") else m.group(1).strip()
    return out


# --- schema 2: performance derivations. Everything here is computed from authored rows (or a
# committed CSV) and is never authored itself; practices/measurement-record.md lists it.
PER_HOUR = {"s": 3600, "min": 60, "hr": 1, "day": 1 / 24}


def vcpus_of(run):
    """The host file's cpus_online first; the size name's arithmetic second. Anything else is truffle's."""
    if run.get("cpus_online"):
        return run["cpus_online"]
    size = run.get("instance", ".").split(".", 1)[1]
    m = re.fullmatch(r"(\d*)xlarge", size)
    return {"medium": 1, "large": 2}.get(size) or (4 * int(m.group(1) or 1) if m else None)


def sig(x, n=4):
    return float(f"{x:.{n}g}")


PLATEAU_MIN = 5


def gpu_summary(path):
    """The plateau rule (#118 v2): threshold = half the series' 90th-percentile sample, so a spike
    shorter than a tenth of the run cannot set it (the first rule, half the MAX, let one startup
    sample make a 53% "plateau" for PME-on-CPU). The active window runs from the first to the last
    sample at or above it, and the plateau is that window's median, derived only when the window
    holds >= PLATEAU_MIN samples. Mean, peak and active fraction alongside: the gap between mean
    and plateau IS the startup artifact. Reads the committed 1 Hz `util%, mem_MB` series
    (headerless, as the GPU scripts write it) or an nvidia-smi --format=csv log with a header."""
    import csv
    rows = [r for r in csv.reader(open(path, encoding="utf-8", errors="replace")) if r and r[0].strip()]
    num = lambda s: float(re.sub(r"[^\d.]", "", s) or 0)
    if re.fullmatch(r"[\d.]+\s*%?", rows[0][0].strip()):
        ui, mi, di = 0, (1 if len(rows[0]) > 1 else None), None
    else:
        head = [h.strip().lower() for h in rows.pop(0)]
        ui = next(i for i, h in enumerate(head) if "utilization.gpu" in h)
        mi = next((i for i, h in enumerate(head) if "memory.used" in h), None)
        di = next((i for i, h in enumerate(head) if h == "index"), None)
    dev = {}
    for r in rows:
        dev.setdefault(r[di].strip() if di is not None else "0", []).append(r)
    out, plats, hbm = {}, [], 0
    for d in sorted(dev):
        u = [num(r[ui]) for r in dev[d]]
        thr = 0.5 * sorted(u)[max(0, -(-9 * len(u) // 10) - 1)]
        act = [i for i, x in enumerate(u) if x >= thr]
        w = sorted(u[act[0]:act[-1] + 1])
        plats.append(sig((w[(len(w) - 1) // 2] + w[len(w) // 2]) / 2, 3) if len(w) >= PLATEAU_MIN else None)
        out.setdefault("util_mean_pct", sig(sum(u) / len(u), 3))
        out.setdefault("util_peak_pct", max(u))
        out.setdefault("active_fraction", sig(len(w) / len(u), 3))
        if mi is not None:
            hbm += int(max(num(r[mi]) for r in dev[d]))
    if plats[0] is not None:
        out["util_plateau_pct"] = plats[0]
    if len(plats) > 1:
        out["per_device_plateau_pct"] = plats
    if mi is not None:
        out["hbm_peak_mib"] = hbm
    return out


SERIES_AXIS = {"workers": lambda r: r.get("workers"), "generation": lambda r: r.get("generation"),
               "chip": lambda r: " ".join(x for x in (r.get("vendor"), r.get("chip")) if x) or r["instance"].split(".")[0],
               "layout": lambda r: f"{r.get('ranks')}x{r.get('threads_per_rank')}",
               "data_path": lambda r: r["data_path"], "concurrent": lambda r: r["concurrent"],
               "gpu_model": lambda r: (r.get("gpu") or {}).get("model"),
               "gpu_count": lambda r: (r.get("gpu") or {}).get("count"),
               "offload": lambda r: ",".join((r.get("gpu") or {}).get("offload", [])) or "none",
               "accelerator": lambda r: ("GPU " + r["gpu"]["model"]) if r.get("gpu") else "CPU " + r["instance"],
               "instance": lambda r: r["instance"]}


def axis_value(r, s):
    return (r.get("size") or {}).get(s.get("size_key", "")) if s["axis"] in ("size", "parameter") else SERIES_AXIS[s["axis"]](r)


def config_key(r):
    """What makes two rows the same configuration: n and spread are derived over it."""
    return json.dumps([r["instance"], r.get("image_resolved", r.get("image")), r.get("build"), r.get("workers"),
                       r.get("ranks"), r.get("threads_per_rank"), r["concurrent"], r.get("size"), r["data_path"],
                       r.get("variant"), r.get("task"), r["purpose"] == "diagnostic",
                       (r.get("gpu") or {}).get("offload")], sort_keys=True)


def curve(e, s):
    """A series' points, speedup and efficiency (numeric axes), and the derived COST knee. The speed
    knee is the author's (verdict.at); no threshold rule derives one."""
    rows = [r for r in e["run"] if s["id"] in r.get("in", []) and r["run_outcome"] == "completed"
            and "superseded_by" not in r]
    pts = [{k: v for k, v in (("axis", axis_value(r, s)), ("instance", r["instance"]), ("id", r.get("id")),
                              ("wall_s", r.get("wall_s")), ("throughput", r.get("throughput")),
                              ("billed_usd", r.get("billed_usd")),
                              ("compute_usd", r.get("compute_usd", r.get("usd_per_result"))), ("n", r["n"]))
            if v is not None} for r in rows]
    if s["axis"] == "instance":
        return {"points": pts}
    if pts and all(isinstance(p["axis"], (int, float)) for p in pts):
        pts.sort(key=lambda p: p["axis"])
        b = pts[0]
        for p in pts:
            sp = p["throughput"] / b["throughput"] if all("throughput" in x for x in (p, b)) else \
                b["wall_s"] / p["wall_s"] if all("wall_s" in x for x in (p, b)) else None
            if sp and s["axis"] == "concurrent" and "throughput" not in p:
                sp *= p["axis"] / b["axis"]       # wall times all N packed jobs: the aggregate rate is N / wall
            if sp:
                p["speedup"] = round(sp, 3)
                if s["axis"] in ("workers", "concurrent") and b["axis"]:
                    p["efficiency"] = round(sp / (p["axis"] / b["axis"]), 3)
    else:
        pts.sort(key=lambda p: str(p["axis"]))
    out = {"points": pts}
    for col in ("billed_usd", "compute_usd"):
        if s["axis"] == "parameter":
            break                                   # a method setting changes the work, so a cheapest rung means nothing
        if len(pts) > 1 and all(col in p for p in pts):
            out["cost_knee"] = {"on": col, "at": min(pts, key=lambda p: p[col])["axis"]}
            break
    return out


def derive_perf(e, mdir):
    """Schema-2 derivations over one record's rows, in place."""
    unit = e.get("throughput_unit")
    per_hr = PER_HOUR[unit.rsplit("/", 1)[1]] if unit else None
    for r in e.get("run", []):
        r.setdefault("run_outcome", "completed")
        r.setdefault("concurrent", 1)
        r.setdefault("data_path", "stage-default")
        tb = e.get("timing", {}).get("billed_basis")
        if tb and (any(k in r for k in ("billed_s", "overhead_s", "billed_usd")) or tb in ("shared-window", "unavailable")):
            r.setdefault("billed_basis", tb)
        v = vcpus_of(r)
        if v:
            r["vcpus"] = v
            if r.get("threads_per_core"):
                r["physical_cores"] = v // r["threads_per_core"]
        if per_hr and "throughput" in r and "usd_hr" in r and r["throughput"]:
            r["usd_per_unit"] = sig(r["usd_hr"] / (r["throughput"] * per_hr))
            if e.get("throughput_is_result"):
                r["usd_per_result"] = round(r["usd_per_unit"], 4)
        if "request_usd" in r:
            r["total_usd"] = round(r.get("billed_usd", 0) + r["request_usd"], 4)
        if {"tool", "stage_in"} <= set(r.get("phase_s", {})):     # a total only when it can be one
            r["phase_total_s"] = sum(x for k, x in r["phase_s"].items() if k not in ("acquire", "source"))
        g = r.get("gpu")
        if g:
            g["offload_basis"] = "log" if "offload_evidence" in g else "flags"
        if g and g.get("util_series") and os.path.exists(os.path.join(mdir, g["util_series"])):
            g.update(gpu_summary(os.path.join(mdir, g["util_series"])))
        util = {}
        if "avg_cores" in r and v:
            util["cpu"] = round(r["avg_cores"] / v, 3)
        if g and "util_plateau_pct" in g:
            util["gpu"] = round(g["util_plateau_pct"] / 100, 3)
        if g and "hbm_peak_mib" in g and "mem_mib" in g:
            util["hbm"] = round(g["hbm_peak_mib"] / (g["mem_mib"] * g["count"]), 3)
        if util:
            r["util"] = util
            r["binding"] = max(util, key=util.get)
            if "usd_hr" in r and util[r["binding"]] > 0:
                r["effective_usd_hr"] = round(r["usd_hr"] / util[r["binding"]], 3)
    groups = {}
    for r in e.get("run", []):
        if r["run_outcome"] == "completed":
            groups.setdefault(config_key(r), []).append(r)
    for rows in groups.values():
        for x in rows:
            x["n"] = len(rows)
            for k in ("wall_s", "throughput"):
                v = [y[k] for y in rows if k in y]
                if len(v) > 1:
                    x[k.split("_")[0] + "_spread"] = [min(v), max(v)]
    for r in e.get("run", []):
        r.setdefault("n", 0)              # a run that did not complete is no sample of its configuration
    pipe = {}
    for r in e.get("run", []):
        if "task" in r and "attempt" in r:
            pipe.setdefault((r["attempt"], r.get("arch", "")), []).append(r)
    res = []
    for (att, arch), rows in sorted(pipe.items()):
        if len({x["task"] for x in rows}) > 1:
            t = {"attempt": att, "arch": arch, "basis": "sum-of-tasks", "tasks": [x["task"] for x in rows]}
            for k in ("wall_s", "billed_s", "compute_usd", "billed_usd"):
                if all(k in x for x in rows):
                    t[k] = round(sum(x[k] for x in rows), 4)
            res.append(t)
    if res:
        e["results"] = res
    for s in e.get("series", []):
        s["curve"] = curve(e, s)


def pin_introduced():
    """{(recipe, pin-token): date that token first appeared in recipes/<r>/README.md}. One git
    call for the whole history; a pin token is a digest or an env_x86_64 name."""
    try:
        log = subprocess.run(["git", "log", "-p", "--reverse", "--format=DATE %as", "-G", r"sha256:|^env_x86_64:",
                              "--", "recipes/*/README.md"], cwd=ROOT, capture_output=True, text=True,
                             check=True).stdout
    except Exception:
        return {}
    first, date, rec = {}, None, None
    for line in log.splitlines():
        if line.startswith("DATE "):
            date = line[5:]
        elif line.startswith("diff --git"):
            m = re.search(r"b/recipes/([^/]+)/README.md", line)
            rec = m.group(1) if m else None
        elif line.startswith("+") and rec:
            for tok in re.findall(r"sha256:[0-9a-f]{64}", line):
                first.setdefault((rec, tok), date)
            m = re.match(r"\+env_x86_64:\s*(\S+)", line)
            if m:
                first.setdefault((rec, m.group(1)), date)
    return first


def recipe_pins(text):
    fm = frontmatter(text)
    arm = [unq(fm["image"])] if fm.get("image") else fm_list(text, "images")
    x86 = fm_list(text, "images_x86_64")
    env = unq(fm.get("env_x86_64", "")) or None
    return arm, x86, env


def recipe_entry(name, d, text, inputs, updated, meas):
    fm = frontmatter(text)
    arm, x86, env = recipe_pins(text)
    specs = []
    for s in sorted(glob.glob(os.path.join(d, "*.task.json"))):
        j = json.load(open(s, encoding="utf-8"))
        specs.append({"path": os.path.relpath(s, ROOT), "container": j.get("container"),
                      "resources": j.get("resources", {}),
                      "lifecycle": {k: v for k, v in j.get("lifecycle", {}).items() if k in ("ttl", "cost_limit")}})
    out = {"path": os.path.relpath(os.path.join(d, "README.md"), ROOT),
           "tool": unq(fm.get("tool")), "tool_version": unq(fm.get("tool_version")),
           "env": unq(fm.get("env")), "spawn_version": unq(fm.get("spawn_version")),
           "pins": {"arm64": arm,
                    "x86_64": x86 or ({"env_lock": f"envs-x86_64/{env}.linux-64.lock"} if env else [])},
           "last_verified": {k: unq(fm.get(f)) for k, f in (("arm64", "last_verified"),
                             ("x86_64", "last_verified_x86_64"), ("amd", "last_verified_amd")) if fm.get(f)},
           "gap": {k: unq(fm.get(f"gap_{k}")) for k in ("arm64", "x86_64") if fm.get(f"gap_{k}")},
           "specs": specs, "inputs": inputs, "measurements": meas, "last_updated": updated}
    return {k: v for k, v in out.items() if v not in (None, {}, [])}


def check_status(c):
    oc = c.get("outcome", "")
    return oc if isinstance(oc, str) else ("fail" if "fail" in oc.values() else "pass")


def measurement_entries(recipe_texts, owners_of):
    import tomllib
    intro = pin_introduced()
    shallow = subprocess.run(["git", "rev-parse", "--is-shallow-repository"], cwd=ROOT,
                             capture_output=True, text=True).stdout.strip() == "true"
    meas, traps, upstream, reverse = {}, [], {}, {}
    for mdir in sorted(glob.glob(os.path.join(ROOT, "measurements", "*/"))):
        name = os.path.basename(mdir.rstrip("/"))
        owners = owners_of(name)
        rpath = os.path.join(mdir, "record.toml")
        if not os.path.exists(rpath):
            meas[name] = {"owners": list(owners), "record": None}
            continue
        rec = tomllib.load(open(rpath, "rb"))
        e = {"path": os.path.relpath(rpath, ROOT), "owners": list(owners),
             "results_per_run": rec.get("results_per_run", 1), **rec}
        for run in e.get("run", []):
            run.setdefault("purpose", "primary")
            run.setdefault("image", "recipe")
            run.setdefault("region", "us-west-2")
            run.setdefault("date_source", "run")
            run.update(chip_of(run.get("instance", "")))
            if "host" in run:
                hf = host_facts(os.path.join(mdir, run["host"]))
                run.update({k: v for k, v in hf.items() if k not in run})
            if run["image"] == "recipe" and owners and run.get("arch") in ("arm64", "x86_64", "amd"):
                arm, x86, env = recipe_pins(recipe_texts[owners[0]])
                toks = arm if run["arch"] == "arm64" else (x86 or ([env] if env else []))
                if toks:
                    run["image_resolved"] = toks if run["arch"] == "arm64" or x86 else f"envs-x86_64/{env}.linux-64.lock"
                keys = [re.search(r"sha256:[0-9a-f]{64}", t).group(0) if "sha256:" in t else t for t in toks]
                dates = [intro.get((owners[0], k)) for k in keys]
                # The pin swap rule made visible: a repin after the run means the run measured
                # other bytes. Not an error -- it is still a true fact about the old ones.
                if toks and not shallow and all(dates):
                    run["pin_current"] = max(dates) <= str(run.get("date"))
        if rec.get("schema") == 2:
            derive_perf(e, mdir)
        e["status"] = "fail-reported" if any(check_status(c) == "fail" for c in e.get("check", [])) else "pass"
        e["unpinned"] = [d["id"] for d in e.get("dataset", []) if "unpinned" in d]
        for t in e.pop("trap", []):
            traps.append({"owner": f"measurements/{name}", **t})
        for u in e.get("upstream", []):
            upstream.setdefault(u["ref"], []).append({"measurement": f"measurements/{name}", "role": u["role"],
                                                      **({"note": u["note"]} if "note" in u else {})})
        for x in e.get("cross_code", []):
            tgt = x["with"].removeprefix("measurements/").rstrip("/")
            reverse.setdefault(tgt, []).append({"from": f"measurements/{name}", "check": x["check"],
                                                "metric": x["metric"]})
        meas[name] = e
    for tgt, links in reverse.items():
        if tgt in meas and "run" in meas[tgt]:
            meas[tgt]["cross_code_from"] = sorted(links, key=lambda l: l["from"])
    hits = {}
    for name, e in meas.items():
        for t in e.get("trap_refs", []):
            hits.setdefault(t, []).append(f"measurements/{name}")
    for t in traps:
        if t["id"] in hits:
            t["also_hit_by"] = sorted(hits[t["id"]])
    return (meas, sorted(traps, key=lambda t: t["id"]),
            [{"ref": r, "uses": sorted(u, key=lambda x: x["measurement"])} for r, u in sorted(upstream.items())])


def main():
    recipes = {}  # name -> dir
    for readme in glob.glob(os.path.join(ROOT, "recipes", "*", "README.md")):
        d = os.path.dirname(readme)
        recipes[os.path.basename(d)] = d

    # prefix -> EVERY recipe whose stage script uploads to it.
    #
    # This was `builder[p] = name`, last-writer-wins over a filesystem-ordered glob -- so a
    # prefix two recipes both stage (inputs/bwa-real/ is built partly by bwa-samtools and
    # partly by bwa-mem2) resolved differently on macOS and on Linux, and the generated
    # catalog was platform-dependent. `make catalog` locally then disagreed with CI's
    # --check forever. A set, emitted sorted, is both deterministic and the truthful answer:
    # when a prefix has two partial builders, name them both.
    builder = {}
    for name in sorted(recipes):
        for p in stage_builds(recipes[name]):
            builder.setdefault(p, set()).add(name)

    rows, rec_recipes = [], {}
    for name in sorted(recipes):
        d = recipes[name]
        text = open(os.path.join(d, "README.md"), encoding="utf-8").read()
        fm = frontmatter(text)
        env = fm.get("env") or ("pipeline" if "images" in fm else "aarchbio")
        domain = env
        prefixes, runs = spec_inputs(d)
        has_own_stage = os.path.exists(os.path.join(d, "stage-inputs.sh"))

        # Two dependency KINDS, because they mean different reader actions — the actionable
        # distinction item 4 exists for, not the mere fact of a dependency:
        #   stage-dep: reads a sibling's *staged input*  -> `make stage RECIPE=<sib>`
        #   run-dep:   reads a sibling's *run output*     -> `make run RECIPE=<sib>` and wait
        stage_deps = {r for p in prefixes for r in builder.get(p, ()) if r != name}
        run_deps = {x for x in runs if x != name}

        # Inference is the default; `depends_on` overrides only where it's wrong or can't see
        # the dependency (e.g. a pure ordering dep). Syntax: `depends_on: stage:bwa-samtools,
        # run:freebayes` — a bare token defaults to a stage-dep. Not required anywhere today.
        if fm.get("depends_on"):
            stage_deps, run_deps = set(), set()
            for tok in re.split(r"[,\s]+", fm["depends_on"]):
                kind, _, rec = tok.partition(":")
                if not (rec or kind):
                    continue
                (run_deps if (rec and kind == "run") else stage_deps).add(rec or kind)

        # A sibling needed as both a stage-dep and a run-dep collapses to the stronger action:
        # `make run RECIPE=X` already requires X staged, so listing both would be redundant
        # (the cross-validation recipes — bowtie2/diamond/kallisto — reuse a sibling both ways).
        stage_targets = (({name} if has_own_stage else set()) | stage_deps) - run_deps
        segs = []
        if stage_targets == {name}:
            segs.append("stage")                                    # `make stage RECIPE=<this>`
        elif stage_targets:
            segs.append("stage: " + ", ".join(sorted(stage_targets)))
        if run_deps:
            segs.append("run: " + ", ".join(sorted(run_deps)))
        inputs = " · ".join(segs) if segs else ("build-in-task" if not (prefixes or runs) else "stage")
        # x86_64: the verifying run's date, or "gap" when the recipe records that no x86
        # build exists -- so this column IS the list of missing x86 builds, generated.
        x86 = fm.get("last_verified_x86_64") or ("gap" if fm.get("gap_x86_64") else "—")
        amd = fm.get("last_verified_amd") or ("gap" if fm.get("gap_x86_64") else "—")
        updated = git_updated(os.path.relpath(d, ROOT))
        rows.append((domain, name, retarget_links(lede(text), d), env, inputs, updated,
                     fm.get("last_verified") or ("gap" if fm.get("gap_arm64") else "fails" if fm.get("fail_arm64") else "—"), x86, amd))
        rec_recipes[name] = (d, text, inputs, updated)

    # group by domain, alphabetical within
    domains = sorted({r[0] for r in rows})
    out = [BANNER, "", "# The recipe catalog", "",
           f"Every recipe here runs one tool on an AWS box, verified, self-terminating "
           f"— **{len(rows)} working examples**, generated from the recipes themselves so this "
           f"list is always what actually ships. Each links to its page; run most with "
           f"`make run RECIPE=<name>` — a **pipeline** recipe (Env `pipeline`) launches through "
           f"its own workflow engine instead, as its page shows, not `make run`.", "",
           "**Inputs** — what a clean-account reader runs *before* `make run`, and the two kinds "
           "are different actions: **build-in-task** (nothing to stage) · **stage** "
           "(`make stage RECIPE=<this>`) · **stage: X** (`make stage RECIPE=X` — this recipe "
           "reuses X's staged input) · **run: X** (`make run RECIPE=X` and wait — this recipe "
           "reads X's run output).", "",
           "**Updated** is the git date of the page's last change (freshness). **Verified** is "
           "the date a real run last confirmed it on Graviton4 (arm64) — `—` means not verified "
           "since tracking began, an honest TODO for the next run, never backfilled; **gap** means "
           "no arm64 build exists, so the recipe is x86-only. **x86_64** is "
           "the same for a same-generation Intel box (`c8i`/`m8i`/`r8i`, `make run ... ARCH=x86_64`): "
           "a date, `—` (not yet run), or **gap** (no x86 build of the pinned version exists; the "
           "page says why). **AMD** is the same pins on same-generation AMD EPYC "
           "(`c8a`/`m8a`/`r8a`, `make run ... ARCH=amd`).", ""]
    for dom in domains:
        drows = [r for r in rows if r[0] == dom]
        out.append(f"## {dom}")
        out.append("")
        out.append("| Recipe | What it does | Env | Inputs | Updated | Verified | x86_64 | AMD |")
        out.append("|---|---|---|---|---|---|---|---|")
        for _, name, desc, env, inputs, updated, verified, x86, amd in drows:
            out.append(f"| [{name}](../recipes/{name}/README.md) | {desc} | {env} | {inputs} | {updated} | {verified} | {x86} | {amd} |")
        out.append("")
    content = "\n".join(out).rstrip() + "\n"

    # Blank the git-derived Updated column before comparing: it advances on every commit that
    # touches a recipe, so gating on it would make the catalog perpetually "stale". Structure,
    # deps, and the hand-set Verified column are still gated.
    # (The Updated cell is the 5th of 8; the regex anchors on the three date-or-gap cells after it.
    # It used to anchor on one, which blanked the x86_64 cell and gated on Updated.)
    def norm(t):
        return re.sub(r"\| (?:\d{4}-\d{2}-\d{2}|—) ((?:\| (?:\d{4}-\d{2}-\d{2}|—|gap) ){3}\|)$",
                      r"| UPDATED \1", t, flags=re.M)

    # catalog/record.json, from the same pass. Its git-derived last_updated is blanked for --check
    # for the same reason as the Updated column.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from check_pages import measurement_owners
    meas, traps, upstream = measurement_entries({n: v[1] for n, v in rec_recipes.items()},
                                                lambda n: measurement_owners(n, set(rec_recipes)))
    owned = {}
    for n in meas:
        for o in meas[n]["owners"]:
            owned.setdefault(o, []).append(f"measurements/{n}")
    record = {"generated_by": "scripts/gen_catalog.py -- do not edit; run `make catalog`",
              "schema": "measurements/record.schema.json", "schema_version": 2,
              "recipes": {n: recipe_entry(n, d, t, i, u, owned.get(n, []))
                          for n, (d, t, i, u) in sorted(rec_recipes.items())},
              "measurements": meas, "traps": traps, "upstream": upstream}
    rec_content = json.dumps(record, indent=1, sort_keys=True, ensure_ascii=False) + "\n"

    def rnorm(t):
        return re.sub(r'"last_updated": "[^"]*"', '"last_updated": ""', t)

    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if norm(current) != norm(content):
            print("catalog/recipes.md is stale — run `make catalog`", file=sys.stderr)
            import difflib
            d = list(difflib.unified_diff(norm(current).splitlines(), norm(content).splitlines(),
                                          "committed", "regenerated", lineterm="", n=0))
            for line in d[:24]:
                print("  " + line, file=sys.stderr)
            if len(d) > 24:
                print(f"  … {len(d) - 24} more diff lines", file=sys.stderr)
            return 1
        print("catalog/recipes.md up to date")
        current = open(RECORD_OUT, encoding="utf-8").read() if os.path.exists(RECORD_OUT) else ""
        if rnorm(current) != rnorm(rec_content):
            print("catalog/record.json is stale — run `make catalog`", file=sys.stderr)
            import difflib
            d = list(difflib.unified_diff(rnorm(current).splitlines(), rnorm(rec_content).splitlines(),
                                          "committed", "regenerated", lineterm="", n=0))
            for line in d[:24]:
                print("  " + line, file=sys.stderr)
            return 1
        print("catalog/record.json up to date")
        return 0
    open(OUT, "w", encoding="utf-8").write(content)
    open(RECORD_OUT, "w", encoding="utf-8").write(rec_content)
    n_rec = sum(1 for m in meas.values() if "run" in m)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(rows)} recipes) and "
          f"{os.path.relpath(RECORD_OUT, ROOT)} ({n_rec} of {len(meas)} measurements recorded)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
