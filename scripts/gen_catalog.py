import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "catalog", "recipes.md")
BANNER = "<!-- GENERATED by scripts/gen_catalog.py — do not edit by hand; run `make catalog`. -->"


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                fm[k.strip()] = v.strip()
    return fm


def lede(text):
    """First prose line after the H1 — the recipe's own one-liner."""
    body = re.sub(r"^---\n.*?\n---\n", "", text, flags=re.S)
    lines = body.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("# "):
            for nxt in lines[i + 1:]:
                if nxt.strip() and not nxt.startswith(("#", ">", "```")):
                    return nxt.strip()
    return ""


CATALOG_DIR = os.path.join(ROOT, "catalog")


def retarget_links(text, recipe_dir):
    """Rewrite a lede's relative links so they resolve from catalog/recipes.md, not from the
    recipe dir the lede was written in: `../mafft/README.md` (correct from recipes/muscle/)
    becomes `../recipes/mafft/README.md`. Ledes are copied verbatim, so without this the one
    artifact nobody hand-edits is the one that carries broken links."""
    def repl(m):
        label, target = m.group(1), m.group(2)
        url = target.split()[0]
        if url.startswith(("http://", "https://", "mailto:", "#")):
            return m.group(0)
        path, _, anchor = url.partition("#")
        if not path:
            return m.group(0)
        newrel = os.path.relpath(os.path.normpath(os.path.join(recipe_dir, path)), CATALOG_DIR)
        return f"[{label}]({newrel}{'#' + anchor if anchor else ''})"
    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, text)


def stage_builds(recipe_dir):
    """Which inputs/<prefix>/ this recipe's stage script uploads to."""
    sh = os.path.join(recipe_dir, "stage-inputs.sh")
    if not os.path.exists(sh):
        return set()
    text = open(sh, encoding="utf-8").read()
    # Attribution needs UPLOAD DESTINATIONS, not any mention. The loose `inputs/<p>` match
    # (which check_pages.py still uses, correctly, to ask only "is this prefix buildable
    # at all") counted comments and echo strings: recipes/abundance says "they already live
    # under inputs/kraken2/ and this recipe reads them there", which made abundance a
    # "builder" of kraken2's prefix. So: drop comments, then require an s3:// destination
    # or a path-variable assignment.
    body = "\n".join(l.split("#", 1)[0] for l in text.splitlines())
    pats = (r"s3://[^/\s\"']*/inputs/([\w.-]+)",
            r"^\s*\w*(?:PREFIX|DST|DEST|TARGET)\w*=\"?[^\"\n]*?inputs/([\w.-]+)")
    found = set()
    for pat in pats:
        found |= {m.group(1) for m in re.finditer(pat, body, re.M)}
    return found


def git_updated(recipe_dir):
    """git commit date of the recipe's last substantive change — page freshness, derived
    not stored (git already knows). Normalized out of --check so it can't cause false stale."""
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cd", "--date=short", "--", recipe_dir],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
        return out or "—"
    except Exception:
        return "—"


def spec_inputs(recipe_dir):
    """(input prefixes read from inputs/<p>/, sibling recipes read from runs/<x>/)."""
    prefixes, runs = set(), set()
    for spec in glob.glob(os.path.join(recipe_dir, "*.task.json")):
        text = open(spec, encoding="utf-8").read()
        prefixes |= {m.group(1) for m in re.finditer(r'"source":\s*"s3://[^/]+/inputs/([\w.-]+)/', text)}
        runs |= {m.group(1) for m in re.finditer(r'"source":\s*"s3://[^/]+/runs/([\w.-]+)/', text)}
    return prefixes, runs


